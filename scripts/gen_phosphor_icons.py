#!/usr/bin/env python3
import os
import re
import sys

from fontTools.ttLib import TTFont

RESERVED = {"INF", "INFINITY", "M_PI", "DOMAIN", "OVERFLOW", "UNDERFLOW", "HUGE", "SING", "NAN", "NULL", "EOF", "TRUE", "FALSE"}
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def icon_names(font):
    cmap = font.getBestCmap()
    gid_to_cp = {}
    for cp, gid in cmap.items():
        if cp >= 0xE000:
            gid_to_cp[gid] = cp
    glyph_char = {gid: chr(cp) for cp, gid in cmap.items() if cp < 0x80}
    result = {}
    for lookup in font["GSUB"].table.LookupList.Lookup:
        for sub in lookup.SubTable:
            if hasattr(sub, "ExtSubTable"):
                sub = sub.ExtSubTable
            if hasattr(sub, "mapping"):
                for src, dst in sub.mapping.items():
                    if src in glyph_char and dst in gid_to_cp:
                        result[glyph_char[src]] = gid_to_cp[dst]
                continue
            if not hasattr(sub, "ligatures"):
                continue
            for first, ligatures in sub.ligatures.items():
                for lig in ligatures:
                    parts = [first] + list(lig.Component)
                    if not all(p in glyph_char for p in parts):
                        continue
                    name = "".join(glyph_char[p] for p in parts)
                    if lig.LigGlyph in gid_to_cp:
                        result[name] = gid_to_cp[lig.LigGlyph]
    return result


def main():
    regular = TTFont(os.path.join(ROOT, "data/fonts/Phosphor.ttf"))
    fill = TTFont(os.path.join(ROOT, "data/fonts/Phosphor-Fill.ttf"))
    names = icon_names(regular)
    fill_names = icon_names(fill)
    seen = {}
    for name in sorted(names):
        ident = re.sub(r"[^A-Za-z0-9]+", "_", name).upper()
        if ident[0].isdigit():
            ident = "N" + ident
        if ident in RESERVED:
            ident += "_"
        if ident in seen:
            continue
        seen[ident] = names[name]
        if fill_names.get(name, names[name]) != names[name]:
            seen[ident] = None
    out = []
    out.append("#ifndef ENGINE_FONT_ICONS_PHOSPHOR_H")
    out.append("#define ENGINE_FONT_ICONS_PHOSPHOR_H")
    out.append("")
    out.append("// Generated by scripts/gen_phosphor_icons.py from data/fonts/Phosphor.ttf. Do not edit.")
    out.append("namespace Ph")
    out.append("{")
    for ident, cp in seen.items():
        if cp is None:
            continue
        out.append('inline constexpr const char %s[] = "\\u%04X";' % (ident, cp))
    out.append("}")
    out.append("")
    out.append("#endif")
    path = os.path.join(ROOT, "src/engine/font_icons_phosphor.h")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("%d icons" % len(seen), file=sys.stderr)


if __name__ == "__main__":
    main()
